NODE = """
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage();
  for (const n of %s) {
    await p.goto('file://%s/' + n + '.html');
    await p.pdf({ path: '%s/' + n + '.pdf', format: 'A4', printBackground: true });
  }
  await b.close();
})();
""" % ([n for n, _ in JOBS], OUT, OUT)

